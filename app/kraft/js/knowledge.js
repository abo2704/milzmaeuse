// Empfehlung, falls die Übung keine eigene hat – nach Bewegungsmuster und Gerät
export function recommendation(ex, k) {
  if (k?.rec) return k.rec;
  const f = ex.fields || [];
  switch (ex.group) {
    case 'Fuß & Reha': return 'Nach Absprache mit dem Physio · lieber häufig und kontrolliert';
    case 'Mobilität': return '5–10 Wdh. bzw. 30–60 s je Seite · vor dem Training oder Laufen';
    case 'Core': return f.includes('t') ? '2–3 Sätze à 20–45 s · Pause 45–60 s' : '2–3 Sätze à 8–15 Wdh. · Pause 45–60 s';
    case 'Arme & Schultern': return '2–3 Sätze à 10–15 Wdh. · Pause 60–90 s';
    case 'Ausdauer': return 'Als Intervall oder Finisher · Intensität dosieren';
    case 'Ganzkörper & Hybrid': return f.includes('d') ? '3–4 Runden à 30–50 m · Pause 90–120 s' : '3 Sätze à 8–12 Wdh. · Pause 60–120 s';
  }
  if (ex.equip === 'kg') return '3 Sätze à 6–15 Wdh. · ab 15 sauberen Wdh. schwerer machen · Pause 90–120 s';
  if (ex.equip === 'lh') return '3–4 Sätze à 6–10 Wdh. · 1–3 Wdh. Reserve · Pause 2–3 Min.';
  return '3 Sätze à 8–12 Wdh. · 1–3 Wdh. Reserve · Pause 90–120 s';
}

